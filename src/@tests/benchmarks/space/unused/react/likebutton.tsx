export function LikeButton() {
  const [n, setN] = useState(0)
  const slice = PAYLOAD.slice(n % 8, (n % 8) + 4)
  const label = slice.map((s) => s.slice(0, 6)).join('')
  return h('button', {
    type: 'button',
    'data-testid': 'likebutton',
    title: label,
    onClick: () => setN((v: number) => v + 1),
  }, `LikeButton:${n}`)
}
